import { MIDDOT } from './middot.js';
export const READ = { pts: 500, xp: 5 };
export const readKey = (id) => 'read:' + id;
export const isRead = (G, id) => !!(G && G.scf && G.scf[readKey(id)]);
/** a stage's entries (the ones its completion opens) */
export const entriesOf = (stage) => MIDDOT.filter((m) => m.at === stage);
export const starOf = (G, stage) => entriesOf(stage).some((m) => isRead(G, m.id));
export const readCount = (G) => MIDDOT.filter((m) => isRead(G, m.id)).length;
