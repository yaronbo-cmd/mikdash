/* ─────────────────────────────────────────────────────────────────────────────
 * kings/geo.js — the sea chart's geography, in [lat, lon], and its projection.
 *
 * The chart is a log-azimuthal "fisheye" centred on Jerusalem: directions are true, distances are compressed
 * logarithmically, so Rome and Adiabene fit on a phone while Jaffa, Akko, Tyre and Sidon stay apart and
 * tappable. Coasts are coarse on purpose (a hand-drawn chart), smoothed by quadratic curves in map.js.
 * ──────────────────────────────────────────────────────────────────────────── */
export const J = [31.778, 35.235];                     // Jerusalem, the Temple Mount
/** coasts are stored as flat [lat×10, lon×10, …] (a 0.1° hand-drawn chart; small in the bundle) */
const D = (a) => { const o = []; for (let i = 0; i < a.length; i += 2) o.push([a[i] / 10, a[i + 1] / 10]); return o; };

/** The chart's frame and projection constants (viewBox W × H). */
export const W = 390, H = 300;
export const P = { cx: 228, cy: 162, s: 85, k: 200, sy: 1.25 };

export function proj(lat, lon, o = P) {
  const dx = (lon - J[1]) * Math.cos(J[0] * Math.PI / 180) * 111.32;
  const dy = (lat - J[0]) * 110.57;
  const r = Math.hypot(dx, dy);
  if (r < 1e-6) return [o.cx, o.cy];
  const f = o.s * Math.log1p(r / o.k) / r;
  return [o.cx + dx * f, o.cy - dy * f * o.sy];
}

